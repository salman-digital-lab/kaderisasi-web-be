import { readFile } from 'node:fs/promises'
import { parseEnv } from 'node:util'
import { randomUUID } from 'node:crypto'
import { spawn } from 'node:child_process'
import { once } from 'node:events'
import pg from 'pg'

// This runner uses only the shared test configuration and an owned schema.
const env = parseEnv(await readFile(new URL('../../docs/.env.test.be', import.meta.url), 'utf8'))
const schema = `google_auth_test_${randomUUID().replaceAll('-', '')}`
const client = new pg.Client({
  host: env.DB_HOST,
  port: Number(env.DB_PORT),
  user: env.DB_USER,
  password: env.DB_PASSWORD,
  database: env.DB_DATABASE,
})
await client.connect()
try {
  await client.query(`CREATE SCHEMA "${schema}"`)
  await client.query(`SET search_path TO "${schema}"`)
  const snapshot = await readFile(
    new URL('../../kaderisasi-admin-be-go/database/schema.sql', import.meta.url),
    'utf8'
  )
  for (const table of ['public_users', 'profiles', 'legacy_members']) {
    const ddl = snapshot.match(
      new RegExp(`CREATE TABLE public\\.${table} \\([\\s\\S]*?\\n\\);`)
    )?.[0]
    if (!ddl) throw new Error(`Missing snapshot table ${table}`)
    await client.query(
      ddl
        .replace(`public.${table}`, `"${schema}".${table}`)
        .replace('id integer NOT NULL,', 'id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,')
    )
  }
  await client.query('ALTER TABLE public_users ADD UNIQUE (email), ADD UNIQUE (member_id)')
  await client.query('ALTER TABLE profiles ADD FOREIGN KEY (user_id) REFERENCES public_users(id)')
  const child = spawn(
    process.execPath,
    ['ace', 'test', 'unit', '--files=tests/unit/google_account.spec.ts'],
    {
      cwd: new URL('../', import.meta.url),
      env: {
        ...process.env,
        ...env,
        NODE_ENV: 'test',
        GOOGLE_AUTH_TEST_SCHEMA: schema,
        PGOPTIONS: `-c search_path=${schema}`,
      },
      stdio: 'inherit',
    }
  )
  const [code] = await once(child, 'exit')
  process.exitCode = code ?? 1
} finally {
  await client.query(`DROP SCHEMA "${schema}" CASCADE`)
  console.log(`Cleaned owned schema: ${schema}; no storage objects created`)
  await client.end()
}
