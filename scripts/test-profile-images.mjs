import { readFile } from 'node:fs/promises'
import { parseEnv } from 'node:util'
import { randomUUID } from 'node:crypto'
import { spawn } from 'node:child_process'
import { once } from 'node:events'
import pg from 'pg'

const env = parseEnv(await readFile(new URL('../../docs/.env.test.be', import.meta.url), 'utf8'))
const schema = `profile_image_test_${randomUUID().replaceAll('-', '')}`
const client = new pg.Client({
  host: env.DB_HOST,
  port: Number(env.DB_PORT),
  user: env.DB_USER,
  password: env.DB_PASSWORD,
  database: env.DB_DATABASE,
})
await client.connect()
try {
  await client.query(`CREATE SCHEMA "${schema}"`)
  await client.query(`SET search_path TO "${schema}"`)
  const snapshot = await readFile(
    new URL('../../kaderisasi-admin-be-go/database/schema.sql', import.meta.url),
    'utf8'
  )
  const ddl = snapshot.match(/CREATE TABLE public\.profiles \([\s\S]*?\n\);/)?.[0]
  if (!ddl) throw new Error('Missing profiles schema snapshot')
  await client.query(
    ddl
      .replace('public.profiles', `"${schema}".profiles`)
      .replace('id integer NOT NULL,', 'id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,')
  )
  const child = spawn(
    process.execPath,
    ['ace', 'test', 'unit', '--files=profile_image.spec.ts', '--files=profile_picture.spec.ts'],
    {
      cwd: new URL('../', import.meta.url),
      env: {
        ...process.env,
        ...env,
        NODE_ENV: 'test',
        PROFILE_IMAGE_TEST_SCHEMA: schema,
        PGOPTIONS: `-c search_path=${schema}`,
      },
      stdio: 'inherit',
    }
  )
  const [code] = await once(child, 'exit')
  process.exitCode = code ?? 1
} finally {
  await client.query(`DROP SCHEMA "${schema}" CASCADE`)
  console.log(`Cleaned owned schema: ${schema}`)
  await client.end()
}
